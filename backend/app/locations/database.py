def search_locations(query: str, limit: int = 10) -> List[Dict[str, Any]]:
    """Search cities by name in English or Telugu, or state name."""
    q = query.strip().lower()
    if not q:
        return CITIES_DATABASE[:limit]

    matches = []
    for city in CITIES_DATABASE:
        if (
            q in city["name"].lower()
            or q in city["name_telugu"]
            or q in city["state"].lower()
            or q in city["state_telugu"]
            or q in city["country"].lower()
        ):
            matches.append(city)
            if len(matches) >= limit:
                break
    return matches


def get_location_by_id(city_id: str) -> Optional[Dict[str, Any]]:
    for city in CITIES_DATABASE:
        if city["id"].lower() == city_id.lower():
            return city
    return None


def get_default_location() -> Dict[str, Any]:
    return CITIES_DATABASE[0]
